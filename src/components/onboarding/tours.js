/** Тур, относящийся к адресу страницы (или null). */
export function tourForPath(pathname) {
  const p = pathname === '/' ? '/' : pathname.replace(/\/+$/, '');
  return Object.values(TOURS).find((t) => t.route === p) || null;
}

