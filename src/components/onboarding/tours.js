// Описания обучающих туров. Сначала общий («Знакомство») — один раз для нового пользователя; затем,
// при первом заходе в раздел, короткий тур именно по этому разделу.
//
// Шаг: { id, title, text, target?, action? }.
//  • target — функция, возвращающая элемент на странице (его подсвечивают). Не нашёлся — шаг показывается
//    по центру экрана, текст остаётся полезным: тур не ломается, если экран чуть изменился.
//  • action — { label, to } кнопка перехода в раздел (на последнем шаге общего тура).
// Тексты опираются на то, что реально есть на экране; метки находятся по видимому тексту, а не по
// внутренним классам, чтобы переименование вёрстки не ломало подсказки.

const visible = (el) => {
  if (!el || !el.getBoundingClientRect) return false;
  const r = el.getBoundingClientRect();
  return r.width > 0 && r.height > 0;
};
const firstVisible = (list) => [...list].find(visible) || null;

export const find = {
  css: (sel) => () => firstVisible(document.querySelectorAll(sel)),
  // Пункт меню (на компьютере — боковая панель, на телефоне — выезжающее меню, если оно открыто).
  nav: (path) => () => firstVisible(document.querySelectorAll(`.sidebar-nav a[href="${path}"], .mobile-drawer a[href="${path}"]`)),
  // Заголовок, подпись, кнопка или вкладка по видимому тексту.
  label: (re) => () => firstVisible(
    [...document.querySelectorAll('h1, h2, h3, h4, .section-title, .calc-section-title, .input-label, label, button, summary, th, a')]
      .filter((el) => re.test((el.textContent || '').replace(/\s+/g, ' ').trim())),
  ),
};

